const NOW = 1_000_000;

class FakeRedis implements RedisLike, RedisStringLike {
  readonly values = new Map<string, string>();
  readonly sets = new Map<string, Map<string, number>>();
  readonly delCalls: string[] = [];
  async get(key: string): Promise<string | undefined> { return this.values.get(key); }
  async set(key: string, value: string, options?: RedisSetOptions): Promise<string | undefined> {
    if (options?.nx && this.values.has(key)) return undefined;
    this.values.set(key, value);
    return 'OK';
  }
  async del(key: string): Promise<void> {
    this.delCalls.push(key);
    this.values.delete(key);
  }
  async zAdd(key: string, ...members: { member: string; score: number }[]): Promise<number> {
    let set = this.sets.get(key);
    if (!set) { set = new Map(); this.sets.set(key, set); }
    let added = 0;
    for (const member of members) {
      if (!set.has(member.member)) added += 1;
      set.set(member.member, member.score);
    }
    return added;
  }
  async zRem(key: string, members: string[]): Promise<number> {
    const set = this.sets.get(key);
    if (!set) return 0;
    let removed = 0;
    for (const member of members) if (set.delete(member)) removed += 1;
    return removed;
  }
  async zCard(key: string): Promise<number> { return this.sets.get(key)?.size ?? 0; }
  async zRange(key: string, start: number, stop: number): Promise<{ member: string; score: number }[]> {
    const rows = [...(this.sets.get(key) ?? new Map())]
      .sort(([a, as], [b, bs]) => as - bs || a.localeCompare(b));
    const from = start < 0 ? Math.max(0, rows.length + start) : start;
    const to = stop < 0 ? rows.length + stop : stop;
    return rows.slice(from, to + 1).map(([member, score]) => ({ member, score }));
  }
  async watch(...keys: string[]): Promise<RedisLeaseTransaction> {
    const snapshots = new Map(keys.map((key) => [key, this.values.get(key)]));
    const zsetSnapshots = new Map(
      keys.map((key) => [key, JSON.stringify([...(this.sets.get(key) ?? new Map()).entries()])])
    );
    const redis = this;
    let deletion: string[] = [];
    let zrem: Array<{ key: string; members: string[] }> = [];
    let zadd: Array<{ key: string; members: { member: string; score: number }[] }> = [];
    let multi = false;
    const tx: RedisLeaseTransaction = {
      async multi() { multi = true; },
      async del(...keys) { deletion = keys; return tx; },
      async zRem(key, members) { zrem.push({ key, members }); return tx; },
      async zAdd(key, ...members) { zadd.push({ key, members }); return tx; },
      async exec() {
        if (!multi) throw new Error('MULTI required');
        if (keys.some((key) =>
          redis.values.get(key) !== snapshots.get(key) ||
          JSON.stringify([...(redis.sets.get(key) ?? new Map()).entries()]) !== zsetSnapshots.get(key)
        )) return [];
        const replies: unknown[] = [];
        for (const key of deletion) {
          await redis.del(key);
          replies.push(1);
        }
        for (const operation of zrem) replies.push(await redis.zRem(operation.key, operation.members));
        for (const operation of zadd) replies.push(await redis.zAdd(operation.key, ...operation.members));
        return replies;
      },
      async discard() { deletion = []; zrem = []; zadd = []; },
    };
    return tx;
  }
}

function input(overrides: Partial<ReconcilePendingInput> = {}): ReconcilePendingInput {
  return {
    subredditName: 'S17Cjn21GT',
    actor: 'Moderator',
    username: 'Target_User',
    recordId: 'pending-1',
    resolution: 'inspect',
    ...overrides,
  };
}

function setup(): { redis: FakeRedis; deps: ReconcilePendingDeps; history: ReturnType<typeof createHistoryStore> } {
  const redis = new FakeRedis();
  const history = createHistoryStore(redis);
  return {
    redis,
    history,
    deps: { history, redis, authorizeActor: vi.fn(async () => true), now: () => NOW },
  };
}

function mirrorDeps(redis: FakeRedis): HistoryMirrorDeps & { update: ReturnType<typeof vi.fn> } {
  const update = vi.fn(async (_subredditName: string, _page: string, _content: string) => undefined);
  return { redis, getWikiPage: async () => undefined, updateWikiPage: update, sleep: async () => undefined, update };
}

async function addPending(history: ReturnType<typeof createHistoryStore>, id = 'pending-1') {
  // The id is generated by the store, so replace the generated id in the test
  // fixture only by using the returned identity in callers.
  return history.append('Target_User', {
    at: NOW,
    rule: 2,
    action: 'ban',
    label: '3 day ban',
    modUser: 'Moderator',
    targetThingId: 't3_post',
    state: 'pending',
  });
}

describe('reconcile pending parsing and safety boundary', () => {
  it('parses exactly one known resolution', () => {
    expect(parsePendingResolution(['inspect'])).toBe('inspect');
    expect(parsePendingResolution(['applied'])).toBe('applied');
    expect(parsePendingResolution(['not-applied'])).toBe('not-applied');
    expect(parsePendingResolution(undefined)).toBeUndefined();
    expect(parsePendingResolution(['inspect', 'applied'])).toBeUndefined();
    expect(parsePendingResolution(['unknown'])).toBeUndefined();
  });

  it('denies production before authorization, lock, or history access', async () => {
    const current = setup();
    const load = vi.spyOn(current.history, 'loadStrict');
    await expect(reconcilePending(current.deps, input({ subredditName: 'RPClipsGTA' }))).resolves.toEqual({ status: 'denied' });
    expect(current.deps.authorizeActor).not.toHaveBeenCalled();
    expect(load).not.toHaveBeenCalled();
    expect(current.redis.values).toEqual(new Map());
  });

  it('requires a definite operator resolution and never exposes an unknown mutation', async () => {
    const current = setup();
    await expect(reconcilePending(current.deps, input({ resolution: 'applied', confirmExternalOutcome: false }))).resolves.toMatchObject({
      status: 'invalid',
    });
    expect(current.redis.values).toEqual(new Map());
  });

  it('inspects an exact pending row without changing it', async () => {
    const current = setup();
    const pending = (await addPending(current.history)).record;
    const outcome = await reconcilePending(current.deps, input({ recordId: pending.id }));
    expect(outcome).toMatchObject({ status: 'inspected', username: 'target_user', record: { id: pending.id } });
    expect((await current.history.loadStrict('target_user'))).toMatchObject({ ok: true, rows: [pending] });
  });

  it('marks only the selected exact row applied and leaves retry-safe history', async () => {
    const current = setup();
    const pending = (await addPending(current.history)).record;
    const outcome = await reconcilePending(current.deps, input({ recordId: pending.id, resolution: 'applied', confirmExternalOutcome: true }));
    expect(outcome).toEqual({ status: 'reconciled', username: 'target_user', recordId: pending.id, resolution: 'applied' });
    const rows = await current.history.loadStrict('target_user');
    expect(rows).toMatchObject({ ok: true, rows: [{ id: pending.id }] });
    if (rows.ok) expect(rows.rows[0]?.state).toBeUndefined();
  });

  it('mirrors a row when reconciliation verifies applied state', async () => {
    const current = setup();
    const mirror = mirrorDeps(current.redis);
    const pending = (await addPending(current.history)).record;
    const deps = { ...current.deps, historyMirror: mirror };

    await expect(reconcilePending(deps, input({ recordId: pending.id, resolution: 'applied', confirmExternalOutcome: true })))
      .resolves.toMatchObject({ status: 'reconciled' });
    expect(mirror.update).toHaveBeenCalledTimes(1);
    expect(mirror.update.mock.calls[0]?.[2]).not.toContain('pending');
  });

  it('removes only the selected row when Reddit definitely did not apply', async () => {
    const current = setup();
    const pending = (await addPending(current.history)).record;
    const outcome = await reconcilePending(current.deps, input({ recordId: pending.id, resolution: 'not-applied', confirmExternalOutcome: true }));
    expect(outcome).toEqual({ status: 'reconciled', username: 'target_user', recordId: pending.id, resolution: 'not-applied' });
    expect(await current.history.loadStrict('target_user')).toEqual({ ok: true, rows: [] });
  });

  it('does not reconcile a missing/non-pending record or bypass a held lock', async () => {
    const current = setup();
    await expect(reconcilePending(current.deps, input({ recordId: '1-000000000000', resolution: 'not-applied', confirmExternalOutcome: true }))).resolves.toMatchObject({ status: 'failed' });
    current.redis.values.set(userActionLockKey('target_user'), 'other-owner');
    const delCallsBeforeHeldLock = [...current.redis.delCalls];
    await expect(reconcilePending(current.deps, input({ recordId: '1-000000000000', resolution: 'inspect' }))).resolves.toMatchObject({ status: 'failed' });
    expect(current.redis.values.get(userActionLockKey('target_user'))).toBe('other-owner');
    expect(current.redis.delCalls).toEqual(delCallsBeforeHeldLock);
  });

  it('makes the safe operator instruction prominent', () => {
    expect(buildReconcilePendingToast({
      status: 'failed',
      detail: 'outcome remains unknown; no change made',
    })).toContain('no change made');
  });
});
